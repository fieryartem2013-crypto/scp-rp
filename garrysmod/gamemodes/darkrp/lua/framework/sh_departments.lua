function SCPF.GetDepartment(id)
	return SCPF.Departments[id]
end

function SCPF.DepartmentJobs(deptID)
	local out = {}
	for _, job in pairs(SCPF.Jobs or {}) do
		if job.department == deptID then out[#out + 1] = job end
	end
	table.sort(out, function(a, b) return (a.sort or 99) < (b.sort or 99) end)
	return out
end

function SCPF.ResearchDepartments()
	local out = {}
	for id, d in pairs(SCPF.Departments) do
		if not d.operational then out[#out + 1] = d end
	end
	table.sort(out, function(a, b) return a.name < b.name end)
	return out
end
