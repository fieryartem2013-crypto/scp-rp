function SCPF.Money(n)
	n = math.floor(tonumber(n) or 0)
	local s = tostring(math.abs(n))
	local out = s:reverse():gsub("(%d%d%d)", "%1 "):reverse():gsub("^ ", "")
	return (n < 0 and "-" or "") .. out .. " " .. SCPF.Currency
end

-----------------------------------------------------------------------------
-- ФОРМАТ ИМЕНИ ПЕРСОНАЖА
-- Формат: "И. Фамилия" (инициал + фамилия) — как в Helix
-----------------------------------------------------------------------------
function SCPF.ValidateName(name)
	if not name or #name < SCPF.NameMinLen then
		return false, "Имя слишком короткое (мин. " .. SCPF.NameMinLen .. " символов)"
	end
	if #name > SCPF.NameMaxLen then
		return false, "Имя слишком длинное (макс. " .. SCPF.NameMaxLen .. " символов)"
	end
	if not name:match("^%u[%a'%-]+ %u[%a'%-]+$") then
		return false, "Формат: «Имя Фамилия» с заглавных букв"
	end
	return true
end

function SCPF.ValidateDesc(desc)
	if not desc or #desc < SCPF.DescMinLen then
		return false, "Описание слишком короткое (мин. " .. SCPF.DescMinLen .. " символов)"
	end
	if #desc > SCPF.DescMaxLen then
		return false, "Описание слишком длинное (макс. " .. SCPF.DescMaxLen .. " символов)"
	end
	return true
end
